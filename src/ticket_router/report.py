"""Step 03 (README sync added step-05) -- regenerates a full markdown
comparison table of every run recorded in results/results.json, written to
results/comparison.md AND (step-05) synced into the root README.md's
"## Results" section, between fixed markers -- so the table in README.md is
always regenerated from results.json, never hand-typed. No model calls, no
scoring -- evaluate.py does that; this script only reads what's already
there and re-renders it. Step-24: also fills README.md's compact headline
table (HEADLINE_RUNS, between its own markers) from the same data.

Run from the repo root:
    .venv\\Scripts\\python.exe src\\ticket_router\\report.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

# Make `ticket_router` importable when this file is run directly
# (`python src/ticket_router/report.py`), not just via `python -m` with
# src/ already on PYTHONPATH.
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from ticket_router.metrics import md_table
from ticket_router.run_meta import COST_BASIS_DESCRIPTIONS

REPO_ROOT = Path(__file__).resolve().parents[2]
RESULTS_DIR = REPO_ROOT / "results"
RESULTS_JSON_PATH = RESULTS_DIR / "results.json"
COMPARISON_PATH = RESULTS_DIR / "comparison.md"
README_PATH = REPO_ROOT / "README.md"

README_MARKER_START = "<!-- RESULTS_TABLE_START (generated by report.py from results/results.json -- do not hand-edit) -->"
README_MARKER_END = "<!-- RESULTS_TABLE_END -->"
HEADLINE_MARKER_START = "<!-- HEADLINE_TABLE_START (generated by report.py from results/results.json -- do not hand-edit) -->"
HEADLINE_MARKER_END = "<!-- HEADLINE_TABLE_END -->"

# The README's compact headline table: exactly these runs, in this order.
HEADLINE_RUNS = [
    ("random-baseline", "Random baseline"),
    ("tfidf-baseline", "TF-IDF + logistic regression"),
    ("api-gpt4o-mini-full-test", "gpt-4o-mini, zero-shot"),
    ("qlora-adapter-ckpt1500", "Qwen2.5-1.5B-Instruct + QLoRA"),
]

ZERO_EPS = 1e-9  # a cost_usd this close to 0 is treated as "0" for footnote purposes


def format_cost_cell(value: float, cost_basis: str) -> str:
    """A 0 total_cost_usd means three different things depending on
    cost_basis (see ticket_router.run_meta) -- tag it inline, right where
    the number is, so it can't be read in isolation as simply "free"."""
    text = f"{value:.4f}"
    if abs(value) < ZERO_EPS:
        text += f" [{cost_basis}]"
    return text


def format_latency_cell(value_ms: float, hardware: str) -> str:
    """Latency numbers from different hardware are not comparable to each
    other -- name the hardware right in the cell, not just in a legend that
    could be read separately from the number."""
    return f"{value_ms:.2f} [{hardware}]"


def build_comparison(all_results: dict) -> str:
    headers = ["run", "split", "n", "exact_match", "invalid_rate",
               "queue_acc", "queue_f1", "priority_acc", "priority_f1",
               "type_acc", "type_f1", "lat_p50_ms", "lat_p95_ms",
               "total_cost_usd", "cost_per_1000_usd"]
    rows = []
    training_notes = []  # (run_name, gpu_hours, note) for runs with a real training cost
    used_cost_bases = set()

    # A "superseded" run (see ticket_router.evaluate/results.json's "superseded" key) is a
    # KNOWN-BAD result -- kept in results.json for the project's own methodology record, never
    # deleted, but excluded from the main comparison table: a reader must never see it sitting
    # next to valid results with no explanation. Listed separately below instead.
    superseded = {name: r for name, r in all_results.items() if r.get("superseded")}
    comparable = {name: r for name, r in all_results.items() if not r.get("superseded")}

    for run_name, r in comparable.items():
        run_meta = r.get("run_meta") or {}
        cost_basis = run_meta.get("cost_basis", "unknown")
        hardware = run_meta.get("hardware", "unknown")
        training_cost = run_meta.get("training_cost") or {"gpu_hours": 0.0, "note": ""}
        used_cost_bases.add(cost_basis)
        if training_cost.get("gpu_hours", 0.0) > 0:
            training_notes.append((run_name, training_cost["gpu_hours"], training_cost.get("note", "")))

        rows.append([
            run_name, r["split"], r["n_gold"],
            f"{r['exact_match_rate']:.2%}", f"{r['invalid_rate']:.2%}",
            f"{r['fields']['queue']['accuracy']:.2%}", f"{r['fields']['queue']['macro_f1']:.4f}",
            f"{r['fields']['priority']['accuracy']:.2%}", f"{r['fields']['priority']['macro_f1']:.4f}",
            f"{r['fields']['type']['accuracy']:.2%}", f"{r['fields']['type']['macro_f1']:.4f}",
            format_latency_cell(r['latency_ms']['p50'], hardware),
            format_latency_cell(r['latency_ms']['p95'], hardware),
            format_cost_cell(r['cost']['total_usd'], cost_basis),
            format_cost_cell(r['cost']['per_1000_usd'], cost_basis),
        ])

    lines = ["# Run comparison\n"]
    if not rows:
        lines.append("_No comparable runs recorded yet in results/results.json._\n")
    else:
        lines.append(md_table(headers, rows))
        lines.append("")

    if not rows and not superseded:
        return "\n".join(lines)

    # --- Footnotes: a reader must not be able to read `0.0000` in the cost columns and
    # conclude a run is "free" in the same sense as any other run with a 0 -- see
    # ticket_router.run_meta for why a 0 means three different things depending on
    # cost_basis, decided BEFORE the fine-tuned adapter was ever scored (PROGRESS.md's
    # step-16 entry), specifically so these categories couldn't be picked to flatter a
    # result nobody had seen yet.
    lines.append("## Notes\n")
    lines.append(
        "`[cost_basis]` next to a 0 cost, and `[hardware]` next to every latency figure, are "
        "generated from each run's `results/<run-name>.run_meta.json` -- not hand-typed.\n"
    )
    lines.append("**What a `[cost_basis]` tag means:**\n")
    for basis in sorted(used_cost_bases):
        description = COST_BASIS_DESCRIPTIONS.get(basis, "not recognized -- see ticket_router.run_meta.")
        lines.append(f"- `{basis}`: {description}")
    lines.append("")

    lines.append(
        "**Training cost** (a one-time cost, not part of any single prediction above -- so it "
        "is not, and cannot be, folded into `latency_ms` or `cost_usd`):\n"
    )
    if training_notes:
        for run_name, gpu_hours, note in training_notes:
            lines.append(f"- `{run_name}`: {gpu_hours:g} GPU-hour(s). {note}")
    else:
        lines.append("- (none of the runs above report GPU training hours)")
    lines.append(
        "\nRuns not listed above required no GPU training step of their own -- either a "
        "pre-trained hosted API model, or (TF-IDF, the random baseline) a fit measured in "
        "seconds of CPU time, not GPU-hours; see each such run's `training_cost.note` in "
        "`results/results.json` for the exact figure.\n"
    )

    if superseded:
        lines.append("## Superseded runs (excluded from the comparison above)\n")
        lines.append(
            "Kept in `results/results.json` for this project's own methodology record -- NOT "
            "deleted -- but excluded from the table above because each one is a known-bad "
            "result, not a fair comparison point. Do not read these numbers as competitive "
            "with the runs above.\n"
        )
        for run_name, r in superseded.items():
            sup = r["superseded"]
            replacement = sup.get("superseded_by")
            replacement_note = f" See `{replacement}` instead." if replacement else ""
            lines.append(f"- **`{run_name}`** (`{r['split']}`, n={r['n_gold']}): {sup['reason']}{replacement_note}")
        lines.append("")

    return "\n".join(lines)


def build_headline(all_results: dict) -> str:
    """Compact table for the top of README.md: HEADLINE_RUNS only, same
    formatters and [tags] as build_comparison(). A run missing from
    results.json is omitted with a printed warning, not silently."""
    headers = ["run", "n", "queue F1", "priority F1", "type F1", "exact match", "invalid",
               "latency p50 ms", "latency p95 ms", "cost / 1000 USD"]
    rows = []
    for run_name, display in HEADLINE_RUNS:
        r = all_results.get(run_name)
        if r is None:
            print(f"WARNING: headline run '{run_name}' not in results.json -- omitted from the headline table.")
            continue
        run_meta = r.get("run_meta") or {}
        cost_basis = run_meta.get("cost_basis", "unknown")
        hardware = run_meta.get("hardware", "unknown")
        rows.append([
            f"{display} (`{run_name}`)", r["n_gold"],
            f"{r['fields']['queue']['macro_f1']:.4f}",
            f"{r['fields']['priority']['macro_f1']:.4f}",
            f"{r['fields']['type']['macro_f1']:.4f}",
            f"{r['exact_match_rate']:.2%}", f"{r['invalid_rate']:.2%}",
            format_latency_cell(r['latency_ms']['p50'], hardware),
            format_latency_cell(r['latency_ms']['p95'], hardware),
            format_cost_cell(r['cost']['per_1000_usd'], cost_basis),
        ])
    return md_table(headers, rows)


def demote_headings(text: str) -> str:
    """One level down for every markdown heading, so the full comparison
    (which opens with its own H1 in comparison.md) doesn't add a second H1
    to README.md."""
    return "\n".join("#" + line if line.startswith("#") else line for line in text.split("\n"))


def replace_between(content: str, start: str, end: str, inner: str) -> str:
    pre = content.split(start)[0]
    post = content.split(end)[1]
    return pre + f"{start}\n{inner}\n{end}" + post


def update_readme(comparison_text: str, headline_text: str) -> None:
    """Sync both generated blocks into README.md, each between its own fixed
    HTML-comment markers, so no table in README.md is ever typed by hand.
    The full comparison block is appended if its markers are missing. The
    headline block is only filled where its markers already exist -- its
    position in the prose is an editorial choice this script won't guess.
    """
    if not README_PATH.exists():
        print(f"Note: {README_PATH} does not exist -- skipping README sync.")
        return

    content = README_PATH.read_text(encoding="utf-8")
    readme_comparison = demote_headings(comparison_text)

    if README_MARKER_START in content and README_MARKER_END in content:
        content = replace_between(content, README_MARKER_START, README_MARKER_END, readme_comparison)
    else:
        block = f"{README_MARKER_START}\n{readme_comparison}\n{README_MARKER_END}"
        content = content.rstrip("\n") + "\n\n" + block + "\n"

    if HEADLINE_MARKER_START in content and HEADLINE_MARKER_END in content:
        content = replace_between(content, HEADLINE_MARKER_START, HEADLINE_MARKER_END, headline_text)
    else:
        print("Note: headline markers not found in README.md -- headline table not synced.")

    README_PATH.write_text(content, encoding="utf-8")
    print(f"Synced results tables into {README_PATH}")


def main() -> None:
    if RESULTS_JSON_PATH.exists():
        all_results = json.loads(RESULTS_JSON_PATH.read_text(encoding="utf-8"))
    else:
        all_results = {}
        print(f"Note: {RESULTS_JSON_PATH} does not exist yet -- writing an empty comparison table.")

    text = build_comparison(all_results)
    print(text)

    RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    COMPARISON_PATH.write_text(text, encoding="utf-8")
    print(f"\nWrote {COMPARISON_PATH}")

    update_readme(text, build_headline(all_results))


if __name__ == "__main__":
    main()
