"""Step 02 -- build the modeling dataset.

Reads ONLY data/raw/aa_dataset-tickets-multi-lang-5-2-50-version.csv. See
data/README.md (generated by this script) for why the other two files
downloaded in step 01 are excluded.

Pipeline: English-only filter -> row-count-per-queue sanity gate -> build
`text` from subject+body -> drop rows with empty body / null targets ->
drop exact-duplicate `text` rows -> stratified 80/10/10 split on `queue`
-> write data/processed/{train,val,test}.parquet, data/processed/label_map.json,
and data/README.md.

Run from the repo root:
    .venv\\Scripts\\python.exe src\\ticket_router\\make_dataset.py   (Windows)
    .venv/bin/python src/ticket_router/make_dataset.py                (POSIX)
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

# ----------------------------------------------------------------------
# Config
# ----------------------------------------------------------------------
REPO_ROOT = Path(__file__).resolve().parents[2]
SOURCE_FILE = REPO_ROOT / "data" / "raw" / "aa_dataset-tickets-multi-lang-5-2-50-version.csv"
OUTPUT_DIR = REPO_ROOT / "data" / "processed"
LABEL_MAP_PATH = OUTPUT_DIR / "label_map.json"
DATA_README_PATH = REPO_ROOT / "data" / "README.md"

TARGET_LANGUAGE = "en"
TARGET_FIELDS = ["queue", "priority", "type"]
ID_PREFIX = "tkt"

# Hard gate: if any queue class has fewer than this many rows after the
# English filter, stop before splitting rather than guess a workaround
# (e.g. merging small classes).
MIN_ROWS_PER_QUEUE_CLASS = 100

# Informational only (not a hard stop): flag if duplicate removal on `text`
# looks unexpectedly large relative to the cleaned English subset.
DUPLICATE_FLAG_PCT = 1.0

SPLIT_RATIOS = {"train": 0.8, "val": 0.1, "test": 0.1}
SPLIT_SEED = 42

# Other two files downloaded in step-01, and why this pipeline ignores them.
# Written verbatim into the generated data/README.md.
EXCLUDED_FILES = {
    "dataset-tickets-german_normalized_50_5_2.csv": (
        "German-only, and its `queue` values are a different, incompatible taxonomy "
        "(42 topic-style classes, e.g. 'Pets & Animals/Pet Services') from the 10-class "
        "queue taxonomy in the chosen file -- combining them would mean training against "
        "two different label spaces."
    ),
    "dataset-tickets-multi-lang-4-20k.csv": (
        "Same schema as the chosen file, but its overlap with the chosen file has not been "
        "verified. Combining unverified-overlap sources risks the same ticket (or a near-"
        "duplicate) landing in two different splits (train/val/test), which would leak "
        "information across the split boundary."
    ),
}


def md_table(headers: list[str], rows: list[list]) -> str:
    def esc(v: object) -> str:
        s = "" if v is None else str(v)
        return s.replace("|", "\\|").replace("\n", " ")

    lines = [
        "| " + " | ".join(headers) + " |",
        "| " + " | ".join("---" for _ in headers) + " |",
    ]
    for row in rows:
        lines.append("| " + " | ".join(esc(v) for v in row) + " |")
    return "\n".join(lines)


def stratified_split(df: pd.DataFrame, stratify_col: str, ratios: dict, seed: int) -> dict:
    """Split `df` into named groups, stratified on `stratify_col`.

    Within each stratum, rows are shuffled with a seeded RNG and cut at the
    rounded ratio boundaries; leftover rows (from rounding) fall into the
    last split name so every row is placed in exactly one split.
    """
    rng = np.random.default_rng(seed)
    names = list(ratios.keys())
    cum = np.cumsum(list(ratios.values()))
    assert abs(cum[-1] - 1.0) < 1e-9, "split ratios must sum to 1.0"

    split_indices: dict = {name: [] for name in names}
    for value in sorted(df[stratify_col].unique()):
        group_idx = df.index[df[stratify_col] == value].to_numpy().copy()
        rng.shuffle(group_idx)
        n = len(group_idx)
        boundaries = [0] + [round(c * n) for c in cum]
        boundaries[-1] = n  # guarantee every row in this stratum is placed
        for name, start, end in zip(names, boundaries[:-1], boundaries[1:]):
            split_indices[name].extend(group_idx[start:end].tolist())
    return split_indices


def main() -> None:
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)

    if not SOURCE_FILE.exists():
        print(f"STOP: source file not found: {SOURCE_FILE}")
        print("Run src/ticket_router/inspect_data.py first to download it.")
        sys.exit(1)

    print(f"Loading {SOURCE_FILE.name} ...")
    raw = pd.read_csv(SOURCE_FILE, low_memory=False)
    n_raw = len(raw)
    raw["id"] = [f"{ID_PREFIX}_{i:06d}" for i in raw.index]
    print(f"  {n_raw} rows loaded")

    # --- English-only filter -------------------------------------------------
    df = raw[raw["language"] == TARGET_LANGUAGE].copy()
    n_english = len(df)
    print(f"English-only filter: {n_english} / {n_raw} rows kept "
          f"({n_english / n_raw:.2%})")

    # --- Queue row-count sanity gate (per instructions: right after the
    # English filter, before anything else touches the data) ----------------
    queue_counts_en = df["queue"].value_counts().sort_index()
    print("\nRow count per queue class (English only):")
    for q, c in queue_counts_en.items():
        print(f"  {q}: {c}")
    small_classes = queue_counts_en[queue_counts_en < MIN_ROWS_PER_QUEUE_CLASS]
    if not small_classes.empty:
        print(f"\nSTOP: {len(small_classes)} queue class(es) have fewer than "
              f"{MIN_ROWS_PER_QUEUE_CLASS} rows after the English filter:")
        for q, c in small_classes.items():
            print(f"  {q}: {c} rows")
        print("Not splitting. No class was dropped or merged as a workaround.")
        sys.exit(1)

    # --- Read allowed label values FROM THE DATA -----------------------------
    # (not from the dataset card; computed on the English subset before any
    # row is dropped, since dropping/deduping in this file does not remove
    # an entire label's rows -- see queue counts above, all well over the gate.)
    observed_labels = {field: sorted(df[field].dropna().unique().tolist()) for field in TARGET_FIELDS}
    print("\nObserved label sets (from data, not the dataset card):")
    for field, values in observed_labels.items():
        print(f"  {field}: {values}")

    # --- Drop rows with empty body or a null target --------------------------
    body_missing = df["body"].isna() | (df["body"].astype(str).str.strip() == "")
    target_missing = df[TARGET_FIELDS].isna().any(axis=1)
    to_drop = body_missing | target_missing
    n_body_missing = int(body_missing.sum())
    n_target_missing = int(target_missing.sum())
    n_dropped_total = int(to_drop.sum())
    print(f"\nDropping rows with empty/null body or null target:")
    print(f"  empty/null body: {n_body_missing}")
    print(f"  null target (queue/priority/type): {n_target_missing}")
    print(f"  total rows dropped (union): {n_dropped_total}")
    df = df[~to_drop].copy()
    print(f"  rows remaining: {len(df)}")

    # --- Build `text` (input) and `has_subject` -------------------------------
    df["has_subject"] = df["subject"].notna()
    n_no_subject = int((~df["has_subject"]).sum())
    print(f"\nRows with no subject (body used alone): {n_no_subject} "
          f"({n_no_subject / len(df):.2%} of remaining rows)")
    subject_filled = df["subject"].fillna("")
    df["text"] = np.where(df["has_subject"], subject_filled + "\n" + df["body"], df["body"])

    # --- Drop exact duplicates on `text` --------------------------------------
    n_before_dedup = len(df)
    df = df.drop_duplicates(subset="text", keep="first").copy()
    n_dup_removed = n_before_dedup - len(df)
    dup_pct = n_dup_removed / n_before_dedup * 100 if n_before_dedup else 0.0
    print(f"\nExact-duplicate rows removed (on `text`): {n_dup_removed} "
          f"({dup_pct:.2f}% of {n_before_dedup})")
    if dup_pct > DUPLICATE_FLAG_PCT:
        print(f"  FLAG: duplicate rate ({dup_pct:.2f}%) exceeds the "
              f"{DUPLICATE_FLAG_PCT}% sanity threshold -- worth a second look.")

    n_final = len(df)
    print(f"\nFinal cleaned row count: {n_final}")

    # --- Stratified split (80/10/10 on queue, seed=42) ------------------------
    split_indices = stratified_split(df, "queue", SPLIT_RATIOS, SPLIT_SEED)
    splits = {name: df.loc[idx].copy() for name, idx in split_indices.items()}

    # Stable-id split-exclusivity check.
    id_sets = {name: set(part["id"]) for name, part in splits.items()}
    names = list(id_sets.keys())
    for i in range(len(names)):
        for j in range(i + 1, len(names)):
            overlap = id_sets[names[i]] & id_sets[names[j]]
            assert not overlap, f"id(s) found in both {names[i]} and {names[j]}: {overlap}"
    all_ids = set().union(*id_sets.values())
    assert len(all_ids) == n_final, "some rows were lost or duplicated across splits"
    print("\nAssertion passed: no id appears in more than one split.")

    # --- Save parquet files ----------------------------------------------------
    OUTPUT_COLUMNS = ["id", "subject", "body", "text", "has_subject", "language",
                       "queue", "priority", "type"]
    for name, part in splits.items():
        out_path = OUTPUT_DIR / f"{name}.parquet"
        part[OUTPUT_COLUMNS].reset_index(drop=True).to_parquet(out_path, index=False)
        print(f"Wrote {out_path} ({len(part)} rows)")

    # --- Save label_map.json ----------------------------------------------------
    LABEL_MAP_PATH.write_text(json.dumps(observed_labels, indent=2, ensure_ascii=False), encoding="utf-8")
    print(f"Wrote {LABEL_MAP_PATH}")

    # --- Summary table -----------------------------------------------------------
    print("\n=== Summary ===")
    summary_rows = [[name, len(part), f"{len(part) / n_final:.2%}"] for name, part in splits.items()]
    summary_rows.append(["TOTAL", n_final, "100.00%"])
    col_widths = [max(len(str(r[i])) for r in summary_rows + [["split", "rows", "pct"]]) for i in range(3)]
    header = ["split", "rows", "pct"]
    def fmt_row(r):
        return "  ".join(str(v).ljust(w) for v, w in zip(r, col_widths))
    print(fmt_row(header))
    print(fmt_row(["-" * w for w in col_widths]))
    for r in summary_rows:
        print(fmt_row(r))

    # --- Generate data/README.md (data card) --------------------------------
    readme_lines = build_data_readme(
        n_raw=n_raw, n_english=n_english, queue_counts_en=queue_counts_en,
        n_body_missing=n_body_missing, n_target_missing=n_target_missing,
        n_dropped_total=n_dropped_total, n_no_subject=n_no_subject,
        n_dup_removed=n_dup_removed, dup_pct=dup_pct, n_final=n_final,
        observed_labels=observed_labels, splits=splits,
    )
    DATA_README_PATH.write_text("\n".join(readme_lines), encoding="utf-8")
    print(f"\nWrote {DATA_README_PATH}")


def build_data_readme(*, n_raw, n_english, queue_counts_en, n_body_missing, n_target_missing,
                       n_dropped_total, n_no_subject, n_dup_removed, dup_pct, n_final,
                       observed_labels, splits) -> list[str]:
    lines = []
    lines.append("# Data card: ticket-router training data\n")

    lines.append("## Source\n")
    lines.append(
        "- Hugging Face dataset: [`Tobi-Bueck/customer-support-tickets`]"
        "(https://huggingface.co/datasets/Tobi-Bueck/customer-support-tickets)\n"
        "- License: **CC-BY-NC-4.0** (Creative Commons Attribution-NonCommercial 4.0) -- "
        "**non-commercial use only**.\n"
        "- The tickets in this dataset are **synthetic** (LLM-generated), not real customer "
        "correspondence.\n"
    )

    lines.append("## Which file was used, and why\n")
    lines.append(
        f"Only `data/raw/aa_dataset-tickets-multi-lang-5-2-50-version.csv` ({n_raw} rows) is used "
        "by `src/ticket_router/make_dataset.py`. The other two files downloaded during step-01 are "
        "excluded:\n"
    )
    for fname, reason in EXCLUDED_FILES.items():
        lines.append(f"- **{fname}**: {reason}")
    lines.append("")

    lines.append("## Preprocessing decisions (in pipeline order)\n")
    lines.append(
        f"1. **Language filter**: kept only rows with `language == \"en\"` -- "
        f"{n_english} / {n_raw} rows ({n_english / n_raw:.2%}). Reason: the chosen file mixes "
        "English and German tickets under the same queue taxonomy; this pipeline builds an "
        "English-only model and the German rows are set aside rather than mixed in.\n"
    )
    lines.append(
        "2. **Queue row-count gate**: after the language filter, every one of the 10 queue "
        f"classes still had at least {MIN_ROWS_PER_QUEUE_CLASS} rows (smallest: "
        f"{queue_counts_en.idxmin()} with {int(queue_counts_en.min())}), so the pipeline proceeded "
        "instead of stopping. See the per-class counts below.\n"
    )
    lines.append(
        "3. **Label values read from the data**, not the dataset card: the card lists `critical` "
        "as a possible priority, but it does not occur anywhere in this file -- only "
        f"`{observed_labels['priority']}` are used. `type` values: `{observed_labels['type']}`. "
        f"All {len(observed_labels['queue'])} `queue` values are kept, none merged or dropped.\n"
    )
    lines.append(
        f"4. **Row drop (empty body / null target)**: {n_dropped_total} rows dropped "
        f"({n_body_missing} for empty/null `body`, {n_target_missing} for a null `queue`/`priority`/"
        f"`type`; a row counted in both is not double-counted in the total). In this file, after the "
        "English filter, that total was 0 -- body and all three target fields were fully populated.\n"
    )
    lines.append(
        f"5. **`text` field**: `subject + \"\\n\" + body`, except when `subject` is null "
        f"({n_no_subject} rows, {n_no_subject / n_final:.2%} of the cleaned data) where `text` is "
        "`body` alone. A boolean `has_subject` column records which case applied for each row, so "
        "the substitution is auditable rather than silent.\n"
    )
    lines.append(
        f"6. **Exact-duplicate removal on `text`**: {n_dup_removed} rows removed "
        f"({dup_pct:.2f}% of the pre-dedup cleaned data). "
        + ("This is within the expected range (step-01 found 0 duplicates on `body` alone across "
           "the whole file)." if dup_pct <= DUPLICATE_FLAG_PCT else
           f"**This exceeds the {DUPLICATE_FLAG_PCT}% sanity threshold and is flagged for review** "
           "-- step-01 found 0 duplicates on `body` alone across the whole file, so a high rate here "
           "would be unexpected.")
        + "\n"
    )
    lines.append(
        f"7. **Stratified split**: 80/10/10 train/val/test, stratified on `queue`, fixed seed "
        f"`{SPLIT_SEED}`. Splitting is done independently within each queue class so every class "
        "keeps its ~80/10/10 proportions in every split, rather than risking a class landing "
        "disproportionately in one split by chance.\n"
    )
    lines.append(
        "8. **Stable `id`**: assigned from each row's position in the raw source CSV "
        "(`tkt_000000`, `tkt_000001`, ...) before any filtering, so an id always traces back to the "
        "same source row across re-runs. Verified programmatically that no id appears in more than "
        "one split.\n"
    )
    lines.append(
        "9. **Columns kept in the output**: `id`, `subject`, `body`, `text`, `has_subject`, "
        "`language`, `queue`, `priority`, `type`. The source file's `answer`, `version`, and "
        "`tag_1..tag_8` columns are dropped -- they are not needed for the queue/priority/type "
        "routing targets this dataset is built for.\n"
    )

    lines.append("## Row counts per split\n")
    rows = [[name, len(part), f"{len(part) / n_final:.2%}"] for name, part in splits.items()]
    rows.append(["TOTAL", n_final, "100.00%"])
    lines.append(md_table(["split", "rows", "pct_of_total"], rows))
    lines.append("")

    lines.append("## Label distribution per split\n")
    for field in TARGET_FIELDS:
        lines.append(f"### {field}\n")
        header = ["value"] + list(splits.keys())
        rows = []
        for value in observed_labels[field]:
            row = [value] + [int((part[field] == value).sum()) for part in splits.values()]
            rows.append(row)
        lines.append(md_table(header, rows))
        lines.append("")

    lines.append("## Reproduce\n")
    lines.append("```\n.venv\\Scripts\\python.exe src\\ticket_router\\make_dataset.py\n```\n")
    lines.append(
        f"Requires `data/raw/aa_dataset-tickets-multi-lang-5-2-50-version.csv` to already be present "
        "(downloaded by `src/ticket_router/inspect_data.py`). Deterministic given a fixed source "
        f"file and `SPLIT_SEED = {SPLIT_SEED}`.\n"
    )

    return lines


if __name__ == "__main__":
    main()
